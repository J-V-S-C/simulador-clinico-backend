from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from models import Disease, Simulation


@dataclass
class SavedSimulation:
    simulation: Simulation
    owner_id: str
    case_id: str
    version: int
    checkpoint: datetime
    clock_changed: bool = False


class Transaction(Protocol):
    def list_cases(self) -> list[tuple[str, Disease]]: ...
    def get_case(self, case_id: str) -> Disease | None: ...
    def create_user(self, user_id: str, email: str, password_hash: str) -> None: ...
    def get_user_by_email(self, email: str) -> tuple[str, str] | None: ...
    def get_user(self, user_id: str) -> str | None: ...
    def create_token(self, token_hash: str, user_id: str, expires_at: datetime) -> None: ...
    def get_token_owner(self, token_hash: str, now: datetime) -> str | None: ...
    def delete_token(self, token_hash: str) -> None: ...
    def create_simulation(self, saved: SavedSimulation) -> None: ...
    def get_simulation(self, simulation_id: str, owner_id: str) -> SavedSimulation | None: ...
    def list_simulations(self, owner_id: str, limit: int, offset: int) -> list[SavedSimulation]: ...
    def save_simulation(self, saved: SavedSimulation) -> None: ...
    def create_report(self, report_id: str, simulation_id: str, interaction_id: str, description: str, response: str, context: str) -> None: ...


class Store(Protocol):
    def transaction(self) -> AbstractContextManager[Transaction]: ...
